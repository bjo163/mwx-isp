// Package invoicedoc renders invoice and payment-receipt documents from their
// stored snapshot. Rendering never calculates financial values: every amount is
// taken from the invoice or payment record that owns it.
package invoicedoc

import (
	"bytes"
	"fmt"
	"strings"
	"time"

	"github.com/go-pdf/fpdf"
)

// Kind distinguishes the document heading.
type Kind string

const (
	// KindInvoice is a payable invoice.
	KindInvoice Kind = "invoice"
	// KindReceipt is a payment receipt.
	KindReceipt Kind = "receipt"
)

// Image is an embedded document image already validated by the caller.
type Image struct {
	Data []byte
	Type string // PNG or JPG
}

// Item is one immutable invoice line.
type Item struct {
	Description string
	Quantity    int64
	UnitPrice   int64
	Total       int64
}

// PaymentLine is one recorded payment shown on a receipt or invoice.
type PaymentLine struct {
	Number    string
	Method    string
	Reference string
	Amount    int64
	PaidAt    time.Time
}

// Document is the complete printable payload. The issuer/template fields come
// from the invoice snapshot; the caller supplies them unchanged.
type Document struct {
	Kind      Kind
	Number    string
	Status    string
	Currency  string
	IssuedAt  time.Time
	DueAt     time.Time
	PeriodFrom time.Time
	PeriodTo   time.Time

	IssuerName    string
	IssuerTaxID   string
	IssuerAddress string
	IssuerEmail   string
	IssuerPhone   string
	BrandName     string
	AccentColor   string
	PaperSize     string
	HeaderText    string
	FooterText    string
	ShowTaxID     bool

	BankName          string
	BankAccountName   string
	BankAccountNumber string
	PaymentNote       string

	CustomerName    string
	CustomerNo      string
	CustomerPhone   string
	CustomerAddress string

	Items      []Item
	Payments   []PaymentLine
	Subtotal   int64
	Total      int64
	PaidAmount int64
	Balance    int64

	Snapshot        bool
	SnapshotVersion int

	Logo *Image
	QR   *Image
}

var monthNames = [...]string{
	"Jan", "Feb", "Mar", "Apr", "May", "Jun",
	"Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
}

// RenderPDF returns a deterministic PDF for the document. The same Document
// always produces the same bytes, so tests can pin historical fidelity.
func RenderPDF(doc Document) ([]byte, error) {
	paper := "A4"
	if strings.EqualFold(strings.TrimSpace(doc.PaperSize), "Letter") {
		paper = "Letter"
	}
	pdf := fpdf.New("P", "mm", paper, "")
	pdf.SetMargins(16, 14, 16)
	pdf.SetAutoPageBreak(true, 20)
	pdf.SetCreationDate(doc.IssuedAt)
	pdf.SetModificationDate(doc.IssuedAt)
	pdf.SetProducer("MWX-ISP", true)
	pdf.SetTitle(documentTitle(doc), true)
	pdf.AliasNbPages("{nb}")

	accent := parseHexColor(doc.AccentColor, [3]int{22, 163, 74})

	pdf.SetFooterFunc(func() {
		pdf.SetY(-14)
		pdf.SetFont("Helvetica", "", 7.5)
		pdf.SetTextColor(110, 118, 128)
		footer := strings.TrimSpace(doc.FooterText)
		if footer == "" {
			footer = "Generated by MWX-ISP"
		}
		pdf.CellFormat(0, 5, text(footer), "", 0, "L", false, 0, "")
		pdf.CellFormat(0, 5, fmt.Sprintf("Page %d of {nb}", pdf.PageNo()), "", 0, "R", false, 0, "")
	})

	pdf.AddPage()
	drawHeader(pdf, doc, accent)
	y := 44.0
	y = drawParties(pdf, doc, y)
	y = drawItems(pdf, doc, y)
	y = drawTotals(pdf, doc, y)
	y = drawPayments(pdf, doc, y)
	drawInstructions(pdf, doc, y, accent)

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func documentTitle(doc Document) string {
	if doc.Kind == KindReceipt {
		return "Receipt " + doc.Number
	}
	return "Invoice " + doc.Number
}

func drawHeader(pdf *fpdf.Fpdf, doc Document, accent [3]int) {
	pageWidth, _ := pdf.GetPageSize()
	left, _, right, _ := pdf.GetMargins()
	width := pageWidth - left - right

	pdf.SetFillColor(accent[0], accent[1], accent[2])
	pdf.Rect(0, 0, pageWidth, 30, "F")
	pdf.SetTextColor(255, 255, 255)

	x := left
	logoWidth := 0.0
	if doc.Logo != nil && len(doc.Logo.Data) > 0 {
		if info := registerImage(pdf, "issuer-logo", doc.Logo); info != nil {
			logoWidth = 26
			height := logoWidth * info.Height() / info.Width()
			if height > 16 {
				height = 16
				logoWidth = height * info.Width() / info.Height()
			}
			pdf.ImageOptions("issuer-logo", x, 7, logoWidth, height, false, fpdf.ImageOptions{ImageType: doc.Logo.Type}, 0, "")
			x += logoWidth + 4
		}
	}
	brand := strings.TrimSpace(doc.BrandName)
	if brand == "" {
		brand = strings.TrimSpace(doc.IssuerName)
	}
	if brand == "" {
		brand = "MWX-ISP"
	}
	pdf.SetFont("Helvetica", "B", 13)
	pdf.SetXY(x, 11)
	pdf.CellFormat(width-logoWidth-45, 8, text(brand), "", 0, "L", false, 0, "")
	pdf.SetFont("Helvetica", "B", 15)
	pdf.CellFormat(45, 8, strings.ToUpper(string(doc.Kind)), "", 0, "R", false, 0, "")

	pdf.SetTextColor(30, 34, 40)
	pdf.SetXY(left, 34)
	pdf.SetFont("Helvetica", "B", 11)
	pdf.CellFormat(width, 5, text(doc.IssuerName), "", 2, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 8.5)
	if doc.IssuerAddress != "" {
		pdf.MultiCell(width*0.6, 4, text(doc.IssuerAddress), "", "L", false)
	}
	contact := strings.TrimSpace(strings.Join(nonEmpty(doc.IssuerPhone, doc.IssuerEmail), "  ·  "))
	if contact != "" {
		pdf.MultiCell(width*0.6, 4, text(contact), "", "L", false)
	}
	if doc.ShowTaxID && strings.TrimSpace(doc.IssuerTaxID) != "" {
		pdf.MultiCell(width*0.6, 4, text("Tax ID: "+doc.IssuerTaxID), "", "L", false)
	}
}

func drawParties(pdf *fpdf.Fpdf, doc Document, y float64) float64 {
	pageWidth, _ := pdf.GetPageSize()
	left, _, right, _ := pdf.GetMargins()
	width := pageWidth - left - right

	if strings.TrimSpace(doc.HeaderText) != "" {
		y = ensureSpace(pdf, y, 14)
		pdf.SetXY(left, y)
		pdf.SetFont("Helvetica", "I", 8.5)
		pdf.SetTextColor(80, 88, 98)
		pdf.MultiCell(width, 4.5, text(doc.HeaderText), "", "L", false)
		y = pdf.GetY() + 3
	}

	y = ensureSpace(pdf, y, 26)
	blockTop := y
	pdf.SetFont("Helvetica", "B", 8.5)
	pdf.SetTextColor(110, 118, 128)
	pdf.SetXY(left, y)
	pdf.CellFormat(width*0.52, 4.5, customerLabel(doc), "", 2, "L", false, 0, "")
	pdf.SetTextColor(30, 34, 40)
	pdf.SetFont("Helvetica", "B", 10)
	pdf.MultiCell(width*0.52, 4.8, text(doc.CustomerName), "", "L", false)
	pdf.SetFont("Helvetica", "", 8.5)
	if doc.CustomerNo != "" {
		pdf.MultiCell(width*0.52, 4.2, text("Customer no. "+doc.CustomerNo), "", "L", false)
	}
	if doc.CustomerAddress != "" {
		pdf.MultiCell(width*0.52, 4.2, text(doc.CustomerAddress), "", "L", false)
	}
	if doc.CustomerPhone != "" {
		pdf.MultiCell(width*0.52, 4.2, text("Phone "+doc.CustomerPhone), "", "L", false)
	}

	metaX := left + width*0.58
	metaWidth := width * 0.42
	metaRows := [][2]string{
		{"Document no.", doc.Number},
		{"Issued", formatDate(doc.IssuedAt)},
	}
	if doc.Kind == KindInvoice {
		metaRows = append(metaRows, [2]string{"Due", formatDate(doc.DueAt)})
		if !doc.PeriodFrom.IsZero() {
			metaRows = append(metaRows, [2]string{"Period", formatDate(doc.PeriodFrom) + " - " + formatDate(doc.PeriodTo)})
		}
	}
	metaRows = append(metaRows, [2]string{"Status", strings.ToUpper(doc.Status)})
	for _, row := range metaRows {
		pdf.SetXY(metaX, blockTop)
		pdf.SetFont("Helvetica", "", 8.5)
		pdf.SetTextColor(110, 118, 128)
		pdf.CellFormat(metaWidth*0.42, 4.8, text(row[0]), "", 0, "L", false, 0, "")
		pdf.SetTextColor(30, 34, 40)
		pdf.SetFont("Helvetica", "B", 8.5)
		pdf.CellFormat(metaWidth*0.58, 4.8, text(row[1]), "", 0, "R", false, 0, "")
		blockTop += 4.8
	}
	if blockTop > y {
		y = blockTop
	}
	return y + 5
}

func drawItems(pdf *fpdf.Fpdf, doc Document, y float64) float64 {
	pageWidth, _ := pdf.GetPageSize()
	left, _, right, _ := pdf.GetMargins()
	width := pageWidth - left - right

	y = ensureSpace(pdf, y, 22)
	columns := []float64{width * 0.52, width * 0.12, width * 0.18, width * 0.18}
	drawTableHeader := func() {
		pdf.SetFillColor(238, 240, 243)
		pdf.SetTextColor(50, 56, 64)
		pdf.SetFont("Helvetica", "B", 8.5)
		pdf.SetXY(left, pdf.GetY())
		headers := []string{"Description", "Qty", "Unit price", "Amount"}
		aligns := []string{"L", "R", "R", "R"}
		for i, header := range headers {
			pdf.CellFormat(columns[i], 7, header, "", 0, aligns[i], true, 0, "")
		}
		pdf.Ln(-1)
	}
	pdf.SetXY(left, y)
	pdf.SetY(y)
	drawTableHeader()

	pdf.SetFont("Helvetica", "", 8.8)
	pdf.SetTextColor(30, 34, 40)
	for _, item := range doc.Items {
		lines := splitLines(pdf, text(item.Description), columns[0]-2)
		rowHeight := 6.2 * float64(len(lines))
		if rowHeight < 6.2 {
			rowHeight = 6.2
		}
		if pdf.GetY()+rowHeight > 277 {
			pdf.AddPage()
			drawTableHeader()
			pdf.SetFont("Helvetica", "", 8.8)
			pdf.SetTextColor(30, 34, 40)
		}
		top := pdf.GetY()
		pdf.SetXY(left, top)
		pdf.MultiCell(columns[0]-2, 5.2, text(item.Description), "", "L", false)
		pdf.SetXY(left+columns[0], top)
		pdf.CellFormat(columns[1], rowHeight, fmt.Sprintf("%d", item.Quantity), "", 0, "R", false, 0, "")
		pdf.CellFormat(columns[2], rowHeight, money(doc.Currency, item.UnitPrice), "", 0, "R", false, 0, "")
		pdf.CellFormat(columns[3], rowHeight, money(doc.Currency, item.Total), "", 0, "R", false, 0, "")
		pdf.SetXY(left, top+rowHeight)
	}
	return pdf.GetY() + 3
}

func drawTotals(pdf *fpdf.Fpdf, doc Document, y float64) float64 {
	pageWidth, _ := pdf.GetPageSize()
	left, _, right, _ := pdf.GetMargins()
	width := pageWidth - left - right
	labelWidth := width * 0.62
	valueWidth := width * 0.20

	rows := [][2]string{{"Subtotal", money(doc.Currency, doc.Subtotal)}}
	if doc.PaidAmount != 0 {
		rows = append(rows, [2]string{"Paid", money(doc.Currency, doc.PaidAmount)})
	}
	if doc.Kind == KindReceipt {
		rows = append(rows, [2]string{"Total", money(doc.Currency, doc.Total)})
	}
	y = ensureSpace(pdf, y, float64(len(rows))*6+10)
	for _, row := range rows {
		pdf.SetXY(left+labelWidth, y)
		pdf.SetFont("Helvetica", "", 9)
		pdf.SetTextColor(80, 88, 98)
		pdf.CellFormat(valueWidth, 6, text(row[0]), "", 0, "R", false, 0, "")
		pdf.SetTextColor(30, 34, 40)
		pdf.CellFormat(valueWidth, 6, row[1], "", 0, "R", false, 0, "")
		y += 6
	}
	pdf.SetXY(left+labelWidth, y)
	pdf.SetFont("Helvetica", "B", 10)
	pdf.CellFormat(valueWidth, 7, "Balance", "", 0, "R", false, 0, "")
	pdf.CellFormat(valueWidth, 7, money(doc.Currency, doc.Balance), "", 0, "R", false, 0, "")
	return y + 9
}

func drawPayments(pdf *fpdf.Fpdf, doc Document, y float64) float64 {
	if len(doc.Payments) == 0 {
		return y
	}
	pageWidth, _ := pdf.GetPageSize()
	left, _, right, _ := pdf.GetMargins()
	width := pageWidth - left - right
	y = ensureSpace(pdf, y, 18)
	pdf.SetXY(left, y)
	pdf.SetFont("Helvetica", "B", 8.5)
	pdf.SetTextColor(110, 118, 128)
	pdf.CellFormat(width, 5, "PAYMENTS", "", 2, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 8.5)
	pdf.SetTextColor(30, 34, 40)
	for _, payment := range doc.Payments {
		if y+6 > 275 {
			break
		}
		pdf.SetXY(left, pdf.GetY())
		line := strings.TrimSpace(strings.Join(nonEmpty(payment.Number, payment.Method, payment.Reference, formatDate(payment.PaidAt)), "  ·  "))
		pdf.CellFormat(width*0.72, 5.5, text(line), "", 0, "L", false, 0, "")
		pdf.CellFormat(width*0.28, 5.5, money(doc.Currency, payment.Amount), "", 0, "R", false, 0, "")
		pdf.Ln(-1)
	}
	return pdf.GetY() + 3
}

func drawInstructions(pdf *fpdf.Fpdf, doc Document, y float64, accent [3]int) {
	if doc.BankAccountNumber == "" && doc.PaymentNote == "" && doc.QR == nil {
		return
	}
	pageWidth, _ := pdf.GetPageSize()
	left, _, right, _ := pdf.GetMargins()
	width := pageWidth - left - right
	boxHeight := 34.0
	if doc.QR != nil {
		boxHeight = 46
	}
	y = ensureSpace(pdf, y, boxHeight+4)
	pdf.SetDrawColor(accent[0], accent[1], accent[2])
	pdf.SetLineWidth(0.4)
	pdf.Rect(left, y, width, boxHeight, "D")
	textWidth := width - 8
	if doc.QR != nil {
		textWidth = width - 46
	}
	pdf.SetXY(left+4, y+4)
	pdf.SetFont("Helvetica", "B", 9)
	pdf.SetTextColor(accent[0], accent[1], accent[2])
	pdf.CellFormat(textWidth, 5, "PAYMENT INSTRUCTIONS", "", 2, "L", false, 0, "")
	pdf.SetFont("Helvetica", "", 8.5)
	pdf.SetTextColor(30, 34, 40)
	if doc.BankAccountNumber != "" {
		bankLine := strings.TrimSpace(doc.BankName)
		if bankLine != "" {
			bankLine += " · "
		}
		bankLine += doc.BankAccountNumber
		if doc.BankAccountName != "" {
			bankLine += " · " + doc.BankAccountName
		}
		pdf.MultiCell(textWidth, 4.4, text(bankLine), "", "L", false)
	}
	if doc.PaymentNote != "" {
		pdf.MultiCell(textWidth, 4.4, text(doc.PaymentNote), "", "L", false)
	}
	pdf.SetFont("Helvetica", "I", 7.5)
	pdf.SetTextColor(110, 118, 128)
	pdf.MultiCell(textWidth, 4, text("Instructions are display-only; record a payment only after the funds are received."), "", "L", false)
	if doc.QR != nil {
		if info := registerImage(pdf, "payment-qr", doc.QR); info != nil {
			qrSize := 34.0
			qrHeight := qrSize * info.Height() / info.Width()
			if qrHeight > qrSize {
				qrHeight = qrSize
				qrSize = qrHeight * info.Width() / info.Height()
			}
			pdf.ImageOptions("payment-qr", left+width-40, y+5, qrSize, qrHeight, false, fpdf.ImageOptions{ImageType: doc.QR.Type}, 0, "")
			pdf.SetFont("Helvetica", "", 6.5)
			pdf.SetXY(left+width-40, y+6+qrHeight)
			pdf.CellFormat(38, 4, "Payment QR", "", 0, "C", false, 0, "")
		}
	}
}

func ensureSpace(pdf *fpdf.Fpdf, y, needed float64) float64 {
	if y+needed <= 275 {
		return y
	}
	pdf.AddPage()
	return pdf.GetY()
}

func registerImage(pdf *fpdf.Fpdf, name string, image *Image) *fpdf.ImageInfoType {
	if image == nil || len(image.Data) == 0 {
		return nil
	}
	return pdf.RegisterImageOptionsReader(name, fpdf.ImageOptions{ImageType: image.Type, ReadDpi: true}, bytes.NewReader(image.Data))
}

func customerLabel(doc Document) string {
	if doc.Kind == KindReceipt {
		return "RECEIVED FROM"
	}
	return "BILL TO"
}

func formatDate(value time.Time) string {
	if value.IsZero() {
		return "-"
	}
	value = value.Local()
	return fmt.Sprintf("%02d %s %d", value.Day(), monthNames[value.Month()-1], value.Year())
}

func money(currency string, amount int64) string {
	sign := ""
	if amount < 0 {
		sign = "-"
		amount = -amount
	}
	digits := fmt.Sprintf("%d", amount)
	var grouped strings.Builder
	for i, digit := range digits {
		if i > 0 && (len(digits)-i)%3 == 0 {
			grouped.WriteByte('.')
		}
		grouped.WriteRune(digit)
	}
	if strings.EqualFold(strings.TrimSpace(currency), "") || strings.EqualFold(strings.TrimSpace(currency), "IDR") {
		return sign + "Rp " + grouped.String()
	}
	return sign + strings.ToUpper(strings.TrimSpace(currency)) + " " + grouped.String()
}

func parseHexColor(value string, fallback [3]int) [3]int {
	value = strings.TrimSpace(strings.TrimPrefix(value, "#"))
	if len(value) != 6 {
		return fallback
	}
	var rgb [3]int
	for i := 0; i < 3; i++ {
		var part int
		if _, err := fmt.Sscanf(value[i*2:i*2+2], "%02x", &part); err != nil {
			return fallback
		}
		rgb[i] = part
	}
	return rgb
}

func nonEmpty(values ...string) []string {
	out := make([]string, 0, len(values))
	for _, value := range values {
		if trimmed := strings.TrimSpace(value); trimmed != "" {
			out = append(out, trimmed)
		}
	}
	return out
}

// text maps arbitrary user text onto the Latin-1 range the built-in
// Helvetica font can render, so odd input never corrupts the page stream.
func text(value string) string {
	var out strings.Builder
	for _, r := range value {
		switch r {
		case '\u2013', '\u2014':
			out.WriteByte('-')
		case '\u2018', '\u2019':
			out.WriteByte('\'')
		case '\u201c', '\u201d':
			out.WriteByte('"')
		case '\u00a0':
			out.WriteByte(' ')
		case '\u2026':
			out.WriteString("...")
		default:
			if r >= 32 && r <= 255 {
				out.WriteRune(r)
			} else {
				out.WriteByte('?')
			}
		}
	}
	return out.String()
}

func splitLines(pdf *fpdf.Fpdf, value string, width float64) []string {
	if strings.TrimSpace(value) == "" {
		return []string{""}
	}
	words := strings.Fields(value)
	lines := make([]string, 0, 2)
	current := ""
	for _, word := range words {
		candidate := word
		if current != "" {
			candidate = current + " " + word
		}
		if pdf.GetStringWidth(candidate) > width && current != "" {
			lines = append(lines, current)
			current = word
			continue
		}
		current = candidate
	}
	if current != "" {
		lines = append(lines, current)
	}
	return lines
}
